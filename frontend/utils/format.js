/* 把数值显示成人看的样子。干什么用：状态栏那个时间、队列那一列耗时，全原型写了四遍同一句算式，改一次要翻四处。
   会错在哪：各处自己拼 `toFixed(1) + 's'`，将来有人把秒改成毫秒显示，就会只改一处、四行队列显示两套单位。
   怎么回来：显示格式只从本文件出。函数逐字照原型的写法搬，输出与现在一模一样（F1 的要求是行为一字不变）。

   2026-10-23 接真服务这一轮换掉两支：
   - durationText(startMs, nowMs) 掐的是本机秒表，而秒表现在只在服务那一侧有（契约 Task.durationMs）；
     留着它＝界面上还有第二个计时起点，跑完那一行的耗时与状态那句"完成"能差出一秒以上。
   - nowStr() 写的是"本机此刻"，而服务回的 lastCheck 是 UTC 的 RFC3339；
     拿本机时刻盖上去＝把"这一条什么时候检的"改成"这一条什么时候被界面看到的"，那是另一件事。
   所以这两支删掉，新增下面那两支；调用点只有 core/api/snapshot.js 一处。 */

/** 队列那一行「耗时」列：服务回的是跑完那一条的毫秒数，还没跑完（含等待、撤掉、跳过）是 0 → 显示一个破折号。
   为什么 0 不写成 "0.0s"：那一行根本没开始干活，界面上"这一条跑了 0.0 秒"是一句假话（契约 v7 那条用例钉的就是它）。 */
export function durationFromMs(ms) {
  const n = Number(ms);
  if (!Number.isFinite(n) || n <= 0) return '';
  return (n / 1000).toFixed(1) + 's';
}

/** 服务回的最近一次检测时刻（UTC 的 RFC3339）换成"09:02:07"那种本机时刻。
   干什么用：树上与详情那一行显示的时间；格式与含义分开冻——契约给可机读的串，显示形状在这里定。
   会错在哪：串空、或根本不是时间（旧壳回了一半字段）时不能显示 "Invalid Date"，那是界面上最大声的错。
   怎么回来：判据只有"这个日期解不解得开"，解不开就留空，由调用方显示破折号／「尚未检测」。 */
export function clockFromIso(iso) {
  if (!iso) return '';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleTimeString('zh-CN', { hour12: false });
}
